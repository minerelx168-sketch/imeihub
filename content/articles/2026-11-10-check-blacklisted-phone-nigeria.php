## Red Flags When Buying a Used Phone in Lagos or Abuja

- **Price far below market.** A near-new flagship at half price is rarely legitimate.
- **Seller refuses a check.** An honest seller will let you verify the IMEI.
- **No box, no receipt, no proof of ownership.**
- **Mismatched IMEI** on the screen, box, and tray.
- **Seller rushes you** or wants to meet only at night or in an unfamiliar place.
- **Phone is iCloud-locked or has an MDM profile.** A blacklist check alone will not reveal this, so run the Apple checks too.

## What If You Already Bought a Blacklisted Phone?

- **Contact the seller** with your evidence and ask for a refund.
- **Keep records**: receipt, chat messages, seller phone number, and the IMEI report.
- **Report fraud** to the Nigeria Police Force or a local police station if the seller refuses to cooperate.
- **Ask your network operator** about device-related restrictions on your SIM.

## If Your Own Phone Is Lost or Stolen

- Report it to the police and keep the report number.
- Contact your network operator to block the SIM.
- Give your IMEI (found on the original box or in your Apple/Google/Samsung account) to your operator so the device can be flagged as lost.

Always keep a photo of your IMEI and box somewhere safe.

