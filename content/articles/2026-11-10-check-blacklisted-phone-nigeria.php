## FAQ

**Can a blacklisted phone work in Nigeria?**
Sometimes it still connects on a network that does not use the shared blacklist, but it can be blocked later and will not work abroad. Do not buy one.

**Can I unblacklist a phone?**
Only the original reporter (owner or carrier) can have the flag removed. Be wary of anyone who promises to "unblock" an IMEI for a fee.

**Does a clean check guarantee the phone is safe?**
It shows the phone is not on the blacklist at that moment. Always also check for iCloud or Google account locks, and inspect the device physically.
