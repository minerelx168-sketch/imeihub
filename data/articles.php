## What Is the KRA IMEI Declaration?

Kenya's regulators require every mobile phone on a local network to be traceable by its **IMEI** (International Mobile Equipment Identity), the unique 15-digit serial number of the handset. Since **January 2025**, travellers arriving in Kenya are expected to declare phones they bring in through the **Kenya Revenue Authority (KRA)** customs process, using the **F88 passenger declaration form** (the paper form, or the electronic declaration where the airport offers it).

The goal is simple: stop smuggled, cloned and stolen handsets, make sure duty is paid on devices that are not for personal use, and keep the national device database accurate.

> Rules and thresholds change. Always confirm the current requirements on the official KRA and Communications Authority of Kenya (CA) websites before you travel.

