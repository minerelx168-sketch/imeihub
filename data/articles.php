## Why the NCA and Operators Care About the IMEI

Every genuine phone has a unique 15-digit IMEI. In Ghana, as elsewhere, that number is used to:

- **Identify the device**: the first 8 digits (the TAC) reveal the brand and model.
- **Block stolen phones**: an operator can ask for a reported IMEI to be barred from its network.
- **Detect counterfeits and clones**: fake handsets often carry a duplicated, invalid or all-zero IMEI.
- **Support consumer protection**: a recorded IMEI helps police and operators trace a device you report lost.

