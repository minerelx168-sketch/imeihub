## Why Kenya Now Asks Travellers About Their Phones

Kenya's customs rules treat mobile phones, laptops and tablets as dutiable goods. Travellers arriving at Jomo Kenyatta International Airport (JKIA), Moi International Airport in Mombasa or other entry points are expected to declare electronic devices to the **Kenya Revenue Authority (KRA)** using the customs baggage declaration, commonly called the **F88 form**. Since January 2025, declaring the **IMEI number** of each phone you bring in has become a key part of that process, because the IMEI is what links a physical handset to Kenya's mobile networks.

> **Important:** Rules, thresholds and forms change. Always confirm current requirements on the official KRA website or at the airport customs desk before you travel. This guide is general information, not legal or tax advice.

## What Is the F88 Form?

The **F88** is the customs declaration form used on arrival. You list goods you are carrying, their value and whether you are bringing anything restricted or dutiable. For phones, the useful details are:

- **Make and model** (for example, Samsung Galaxy S24 or iPhone 15)
- **IMEI number** (15 digits, one per SIM slot on dual-SIM phones)
- **Approximate value** and whether the phone is for personal use
- **Your passport and contact details**

## What Is an IMEI and Why Does KRA Care?

An **IMEI (International Mobile Equipment Identity)** is a unique 15-digit number assigned to every phone. Regulators use it to:

- Tell genuine phones from counterfeit or cloned ones
- Block stolen devices from local networks
- Make sure duty is paid on imported handsets
- Link a device to the owner who declared it

Without a declared and valid IMEI, a phone can be questioned at customs or, in the worst case, restricted from working on local networks.

## How to Find Your IMEI Before You Land

Do this at home, not in the arrivals queue:

- Dial **\*#06#** on the keypad. Every IMEI appears on screen.
- Open **Settings → About phone → IMEI** (Android) or **Settings → General → About** (iPhone).
- Check the SIM tray or the original box label.
- Take a screenshot and keep a copy offline in case your battery dies.

## Run an IMEI Check Before Declaring

Declaring a phone you cannot prove is yours is risky. Before you travel, or before you buy a second-hand phone in Nairobi, verify the device:

