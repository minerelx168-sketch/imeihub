## KRA IMEI Declaration in Kenya: What Travellers Must Know

If you are flying into Jomo Kenyatta International Airport (JKIA), Moi International Airport or any other Kenyan port of entry with a smartphone, you may be asked to **declare the device and its IMEI number** to the Kenya Revenue Authority (KRA). Since January 2025, phone declaration at the border has become a much more visible part of the arrival process, and travellers who ignore it risk delays, questions from customs officers, or a phone that cannot be activated on local networks.

