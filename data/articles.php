## Common Mistakes Travellers Make

- **Not knowing the IMEI.** Officers may check the number against your paperwork.
- **Carrying multiple new phones "as gifts".** Quantity can make customs treat them as commercial imports.
- **Buying a cheap second-hand phone abroad** without checking whether it is reported lost or stolen.
- **Ignoring the second IMEI** on dual-SIM phones. Declare both if asked.
- **Relying on social-media rumours** instead of official KRA notices.

## Why IMEI Checks Matter Even After You Clear Customs

Kenya's communications regulator and mobile operators use IMEI data to fight device theft, counterfeit handsets and the use of illegal devices on local networks. A phone reported stolen in another country can still be flagged in global databases. Checking the IMEI protects you whether you are a traveller, a returning resident or a buyer on the local second-hand market.

