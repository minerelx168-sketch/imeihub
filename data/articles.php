## After You Arrive: Using Your Phone in Kenya
Kenyan mobile operators and the Communications Authority of Kenya (CA) work to block devices reported stolen. A clean IMEI means your phone should connect to local networks normally. If a SIM stops working on a phone you bought locally, check the IMEI status first.

