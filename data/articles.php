**Do I need to declare a phone I use myself?** Treat it as yes. Declaring is the safe choice, and officers decide what is dutiable.

**What if my phone has two IMEIs?** Record both. Dual-SIM phones have one per SIM slot.

**Can a blacklisted phone be fixed?** Only the party who reported it can usually clear it. Avoid buying it.

**Is the free check enough?** It confirms the model and that the IMEI is well formed. Add the blacklist check before you hand over money.

