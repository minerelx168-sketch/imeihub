## Do You Have to Pay Duty on Your Own Phone?

Personal items used by the traveller are generally treated more leniently than new goods brought in for sale, but customs officers assess this case by case. Factors include:

- Whether the phone is clearly **used and personal**
- The number of devices (one phone is very different from five)
- Whether the phone is **new in box**
- The declared value

If you are unsure, declare honestly. Under-declaring can lead to penalties, seizure or delays, and it is far cheaper to explain a phone than to argue about one.

