## What Happens If You Don't Declare?

- The phone may be **detained** until duty is paid.
- A **penalty** on top of the duty can apply for under-declaration.
- A device not recognised by the DVS can be **switched off by operators** such as Safaricom, Airtel and Telkom.

Declaring takes a few minutes. Seizure or a blocked phone can cost far more.

