## Why Kenya Cares About Your Phone's IMEI

If you are flying into Nairobi (JKIA), Mombasa (MIA) or Kisumu with a new smartphone, a second phone or a handset you bought abroad, your **IMEI number** matters more than ever. Kenyan authorities track mobile devices to fight counterfeits, theft and under-declared imports. Since **January 2025**, travellers have been urged to **declare phones and other electronics** to Kenya Revenue Authority (KRA) customs on arrival, and handsets are matched against the national **Device Verification System (DVS)** run by the Communications Authority of Kenya (CA).

