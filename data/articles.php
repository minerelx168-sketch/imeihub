## Duty and Value Thresholds

Reports on the rollout indicate that returning residents can use personal devices **duty-free if their value is below roughly USD 2,000**, while higher-value devices may attract import duty and VAT. Used phones are assessed at their market value, so an accurate model name and storage size matters. Undeclared or under-declared devices risk **seizure, penalties or network blocking**.

## How to Find Your IMEI Before You Fly

You need the IMEI before filling in the F88. Any of these work:

- Dial **\*#06#** on the keypad
- **iPhone:** Settings > General > About
- **Android:** Settings > About phone > Status information
- Look at the SIM tray or the original box label

Dual-SIM phones have **two IMEIs** - write down both.

