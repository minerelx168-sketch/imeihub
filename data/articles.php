## KRA IMEI Declaration in Kenya: What Changed

Since **January 2025**, the Kenya Revenue Authority (KRA) has required travellers arriving in Kenya to **declare the IMEI number of mobile devices** they bring in, using the customs **F88 declaration form**. The aim is to stop smuggled, under-valued and counterfeit handsets, close tax gaps, and help the Communications Authority of Kenya (CA) block stolen devices.

If you are flying into Nairobi (JKIA), Mombasa (Moi International) or Kisumu with a phone, tablet or smartwatch with a SIM slot, you need to know the rules **before** you land.

