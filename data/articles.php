2. **Confirm the IMEI is genuine.** The 15-digit number must pass the Luhn checksum and match the model printed on the box and under the battery or SIM tray. Use our [Free IMEI Check](https://imeihub.net/service.php?slug=free-imei-check) to confirm brand, model and specs in seconds.
