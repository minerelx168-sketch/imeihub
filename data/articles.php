## Why Kenya Now Cares About Your Phone's IMEI

If you are flying into Jomo Kenyatta International Airport (JKIA), Moi International Airport in Mombasa or any other Kenyan border point with a new phone, you may be asked to **declare the device to the Kenya Revenue Authority (KRA)**. Since January 2025, travellers have been expected to declare personal electronics, including smartphones, using the customs **F88 declaration form**, and the phone's **IMEI number** is the key identifier that links a device to its owner and its duty status.

