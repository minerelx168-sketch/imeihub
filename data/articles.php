## Red Flags When Buying a Used Phone in Ghana

- **A price far below market.** Stolen and cloned phones are usually cheap.
- **A seller who refuses to let you check the IMEI** or insists on a quick deal.
- **A scratched, covered or missing IMEI label.**
- **An IMEI that does not match the model**, such as a fake flagship sold as the real thing.
- **A phone that is "factory unlocked" with no proof**, especially for iPhones.
- **No receipt.** Ask for the seller's name, number and a written note listing the IMEI.

## What to Do If Your Phone Is Stolen in Ghana

- **Report to the police** and keep a copy of the report.
- **Contact your operator** (MTN, Telecel or AT) with your IMEI and ask them to block the handset and SIM.
- **Secure your accounts**: lock your Mobile Money wallet, change passwords and email.
- **For iPhones,** enable Lost Mode through Find My. **For Android,** use Find My Device.
- **Keep proof of purchase.** Photograph the box label and receipt the day you buy, because that is where your IMEI is recorded.

