## Verifying a Phone on Kenyan Networks
Kenya's Communications Authority (CA) runs a device verification system to identify genuine, registered handsets and flag counterfeit or stolen ones. Verification options have included an SMS-based check to the CA short code and the operators' own tools. Because channels and short codes can change, confirm the current method on the CA website.

If you buy a used phone locally, ask the seller to show the IMEI via `*#06#`, compare it with the box and the phone's settings, and run it through a blacklist check **before paying**.

## Common Mistakes Travellers Make
- **Not declaring a new, boxed phone** — sealed devices are the most likely to be treated as commercial goods.
- **Carrying several phones** without a clear reason — multiple devices can trigger questions.
- **Mismatched IMEIs** between the box, the phone and the receipt — a red flag for counterfeits or swapped devices.
- **Buying a used phone without a blacklist check** — it may be blocked after a few days.
- **Assuming the rules never change** — always verify before each trip.

