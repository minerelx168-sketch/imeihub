## Why Kenya Now Cares About Your Phone's IMEI

If you are flying into Jomo Kenyatta International Airport (JKIA), Moi International Airport or any other Kenyan border point, your phone is no longer "just a phone" to customs. The **Kenya Revenue Authority (KRA)** and the **Communications Authority of Kenya (CA)** both use the **IMEI (International Mobile Equipment Identity)** to confirm that a handset is genuine, duty-compliant and not reported stolen.

Since January 2025, travellers have been expected to **declare electronic devices** on arrival, using the customs passenger declaration (commonly referred to as the **F88 form**). This guide explains what that means in practice and how to prepare your phone so you are not delayed, taxed twice or have the device blocked.

> **Important:** Rules, allowances and form names are updated by KRA and the Communications Authority from time to time. Always confirm the latest requirements on the official KRA website or at the customs desk before you travel. This article is general information, not legal or tax advice.

## What Is the F88 Declaration?

The F88 is the passenger customs declaration used to tell Kenyan customs what you are carrying. For phones and other electronics, it is where you list:

- The **make and model** of each device
- The **IMEI number(s)** (a dual-SIM phone has two)
- Whether the device is **new or used**
- Whether it is for **personal use** or for resale / commercial purposes
- The approximate **value** of the item

Declaring honestly matters. Unlisted devices that are discovered during screening can be **detained, taxed and fined**, and a phone with an IMEI that does not match your declaration will raise questions.

## How to Find Your IMEI (Takes 10 Seconds)

Do this *before* you reach the airport:

- **Dial `*#06#`** on any phone. The IMEI(s) appear on screen.
- **iPhone:** Settings → General → About → scroll to *IMEI*.
- **Android:** Settings → About phone → *IMEI information*.
- **Physical check:** The IMEI is printed on the SIM tray, the retail box and the back of many older models.

Write the 15-digit number down or screenshot it. If your phone has two SIM slots, record **both** IMEIs.

