## What Is the F88 Form?
The **F88** is the standard customs declaration form completed by arriving passengers. You state what you are carrying, its value, and whether anything is dutiable or restricted. For phones, the key fields are:

- **Item description:** brand and model (for example, "Samsung Galaxy S24").
- **IMEI number:** the 15-digit identifier of each phone, tablet or cellular smartwatch.
- **Value:** purchase price or current market value.
- **Purpose:** personal use, gift, or resale (commercial).

## Do You Need to Declare Your Phone?
In practice, officers focus on devices that look like they are being **brought in for sale** or that are **new and unused**. As a rule of thumb:

| Situation | Declare? | Likely outcome |
