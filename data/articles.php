## What Is the F88 Form?

The **F88** is the standard Kenyan customs declaration form completed by arriving passengers. It lists goods you carry, including electronics. Under the IMEI rule, you write down:

- The **device type** (phone, tablet, etc.)
- The **make and model**
- The **IMEI number** (15 digits)
- The **approximate value** of the device

KRA has been moving this process online, so devices can be matched automatically against the national device database and unrecognised IMEIs get flagged.

