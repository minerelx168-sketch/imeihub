## Common Mistakes at the Airport

- **Not declaring a new phone.** An unopened device with a receipt is the most obvious dutiable item.
- **Writing the wrong IMEI.** A single wrong digit makes the record useless. Copy it from `*#06#`, not from the box of a different unit.
- **Buying a used phone abroad without checking it.** Sellers can hide a blacklist report or a lock until after you pay.
- **Arriving with no proof of ownership.** An invoice settles most questions quickly.

## After You Arrive: Using the Phone on Kenyan Networks

Once you are through customs, a phone registered with your local SIM should work normally. If a handset is later reported stolen, the IMEI can be blocked, which is why buying second-hand in Nairobi, Mombasa or Kisumu without a check is risky. Before paying a seller, ask for the IMEI, run both checks above, and confirm the number on the phone matches the number on the box.

