## What Is the KRA F88 Form?

The **F88 is the customs declaration form** used by travellers entering Kenya. It asks you to list goods you are carrying, including items that may attract import duty. For phones, the details that matter most are:

- **Device make and model** (for example, "Samsung Galaxy S24")
- **IMEI number** (15 digits, found by dialling `*#06#`)
- **Approximate value** and whether it is new or used
- **Whether it is for personal use** or for resale

Declaring honestly is always cheaper than being caught with an undeclared device. Undeclared goods can be seized or charged penalties on top of duty.

## How to Find Your IMEI Before You Travel

Do this at home, not in the arrivals queue:

- Step 1: Open your phone's dialler and enter `*#06#`. The IMEI(s) appear on screen. Dual-SIM phones show two numbers.
- Step 2: Alternatively go to **Settings > About phone > IMEI** (Android) or **Settings > General > About** (iPhone).
- Step 3: Take a screenshot or note the numbers, and compare them with the sticker on the box or the SIM tray.
- Step 4: Keep your purchase receipt or invoice. It supports the value you declare.

## Check the IMEI Before You Declare It

