## Registering a Phone Brought Into Myanmar

Travellers and returning residents arriving at Yangon, Nay Pyi Taw or Mandalay airports with an unregistered phone should follow this process:

- **Step 1:** Declare the phone at the customs counter and submit the **Passenger Declaration Form (PD Form)** including the IMEI of each phone.
- **Step 2:** Submit a CEIR registration application to the CEIR OSS team with your passport photo page, the arrival-stamp page, your boarding pass and airline ticket, and the original PD Form.
- **Step 3:** Pay the applicable taxes. Applications are reported to be due within **30 days** of filing the PD Form; late applications can attract extra penalties.
- **Step 4:** Wait for confirmation that the IMEI has been added to the whitelist, then insert a SIM and test.

Reports also indicate a limit of **two mobile phones per traveller** (including the one in use). Keep your documents and receipts until the phone is confirmed active.

## Common Reasons a Phone Gets Blocked

- The IMEI was never registered after entering the country.
- The phone has a **cloned or duplicated IMEI**.
- The device is reported **lost or stolen** in another country's database.
- The IMEI printed on the box does not match the one inside the phone.
- A typing mistake on the application form.

