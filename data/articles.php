The key idea: **a phone you use yourself is generally not the problem. Multiple, new or boxed devices are.**

## How to Find Your IMEI

You need the 15-digit IMEI to complete the declaration. Any of these methods works:

- Dial **\*#06#** on the keypad. The IMEI appears on screen.
- **iPhone:** Settings → General → About → scroll to *IMEI*.
- **Android:** Settings → About phone → *IMEI information*.
- Look at the **box label** or the **SIM tray** of the phone.

Dual-SIM phones have **two IMEIs**. Write down both.

