## What Is the F88 Form?

The **F88** is the passenger/baggage declaration form used by Kenyan customs. Travellers use it to declare goods they are bringing into the country, including:

- Mobile phones, tablets, smartwatches and laptops
- Goods bought abroad for gift or resale
- Cash above the reportable limit
- Restricted or prohibited items

For a phone, the form typically asks you to describe the device (brand, model), its **serial number or IMEI**, and whether it is for personal use or commercial purposes.

## What Is a KRA IMEI Declaration?

The **IMEI (International Mobile Equipment Identity)** is the unique 15-digit number of your handset. Declaring the IMEI lets customs and the telecom regulator tie a specific device to a specific traveller. In practice this helps:

- Prove that a phone is **personal-use** rather than a commercial import
- Avoid your genuine phone being mistaken for a new, undeclared shipment
- Support the Communications Authority of Kenya (CA) in blocking **counterfeit or non-compliant devices** from local networks

Keep in mind that a phone you already **own and use** (for example a phone you travelled out with) is generally treated differently from a new phone bought abroad to sell. If in doubt, declare it.

## How to Find Your IMEI in 10 Seconds

You can retrieve your IMEI on almost any phone:

- **Dial `*#06#`** on the keypad – the IMEI appears instantly (dual-SIM phones show two).
- **iPhone:** Settings → General → About → scroll to *IMEI*.
- **Android:** Settings → About phone → *IMEI information*.
- **Physical check:** look at the SIM tray, the back of the phone or the original box label.

Write the IMEI down and make sure it matches the box. A mismatch is a red flag for a refurbished, cloned or counterfeit device.

