## What Is the KRA IMEI Declaration?
Kenya Revenue Authority (KRA) customs officers expect travellers to declare electronic devices they bring into the country. Since January 2025, the declaration of phones, tablets and laptops (including their **IMEI** or serial numbers) has been a much more visible part of airport arrival procedures at Jomo Kenyatta International Airport (JKIA) and other entry points.

The aim is to separate genuine personal-use devices from goods imported for resale, and to curb counterfeit, stolen and smuggled handsets entering the Kenyan market.

> **Note:** Customs rules, thresholds and forms change. Always confirm current requirements on the official KRA website or with a customs officer before you travel.

## What Is the F88 Form?
The **F88** is the standard customs declaration form used on arrival in Kenya. You list goods you are carrying that may be dutiable, restricted, or that exceed personal allowances. For phones and other electronics, travellers are generally asked to provide:

- Device type (smartphone, tablet, laptop, smartwatch)
- Brand and model
- **IMEI number** (15 digits) or serial number
- Whether the device is for personal use or for sale
- Approximate value

## How to Find Your IMEI Before You Land
You need the IMEI ready before you reach the customs desk. Any of these methods works:

- Dial **\*#06#** on the phone keypad.
- **iPhone:** Settings → General → About → scroll to IMEI.
- **Android:** Settings → About phone → IMEI.
- Look at the SIM tray or the original box label.

Dual-SIM phones have **two IMEIs**. Write down both.

