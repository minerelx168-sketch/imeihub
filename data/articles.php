## What Is the KRA IMEI Declaration?

In November 2024 the **Kenya Revenue Authority (KRA)**, working with the **Communications Authority of Kenya (CA)**, announced that passengers entering Kenya from **1 January 2025** would have to list the **IMEI numbers** of mobile devices they carry on the **F88 passenger declaration form**. The stated goal was tax compliance: matching each handset that connects to a Kenyan network with proof that import duty was settled.

The rule drew strong public and tourism-sector reaction. Later reports described exemptions for visitors using foreign roaming SIMs, while other reports said the requirement was scaled back or withdrawn. **Because the position has changed more than once, always confirm the current rule on KRA's official public notices page or with KRA/CA before you travel.**

## Why Kenya Cares About Your IMEI

Every phone has a unique 15-digit **IMEI** (International Mobile Equipment Identity). Regulators use it to:

- Block **stolen** and **counterfeit** handsets from local networks
- Confirm **duty and VAT** were paid on imported devices
- Keep a register of devices that are legally in the country

## What Is the F88 Form?

The **F88** is the customs passenger declaration form completed on arrival. It asks about currency, goods for resale and items above your duty-free allowance. Under the IMEI directive, a section for mobile devices and their IMEI numbers was added.

## How to Find Your IMEI in 10 Seconds

- Dial **\*#06#** on any phone: the IMEI appears on screen
- **iPhone:** Settings > General > About
- **Android:** Settings > About phone > Status information
- Check the SIM tray or the back of the device (older models)
- Dual-SIM phones show **two IMEIs**: note both

