## Personal Use vs. Commercial Quantity

Customs officers distinguish between a traveller carrying their own device and someone importing phones to sell.

| Situation | Typical Treatment | What to Prepare |
|---|---|---|
| One phone for personal use | Usually declared and cleared, subject to current allowances | IMEI, receipt, declaration |
| Phone plus a spare or gift | Each device must be declared | IMEIs for all devices |
| Several phones of the same model | Treated as possible commercial import | Full declaration, expect duty |
| Used phone bought abroad | Declared as used; value assessed | Receipt, IMEI, condition |

## Why a Clean IMEI Protects You

A mismatched, cloned or blacklisted IMEI is the most common reason a traveller's phone gets stuck. Checking first helps you avoid three expensive problems:

- **Blacklisted devices:** Reported lost or stolen phones can be barred from networks.
- **Counterfeit or cloned IMEIs:** Kenya's device management system is designed to detect and disable fake handsets.
- **Wrong model on paper:** If the declared model differs from what the IMEI resolves to, expect extra scrutiny.

## Buying a Used Phone in Kenya? Check It Too

