## Frequently Asked Questions

**Do I need to declare a phone I already own?**
Requirements differ between residents, visitors and returning citizens, and they can change. Check the latest KRA guidance or ask a customs officer. When in doubt, declare.

**Where do I find the IMEI on a locked phone?**
Look at the SIM tray, the back of the device, or the original box. On iPhones, the IMEI is also engraved on the SIM tray of many models.

**Can an IMEI check tell me the duty I will pay?**
No. An IMEI check identifies the device and its status. Duty is calculated by KRA from the declared value and applicable rates.

**What if my phone shows as blacklisted?**
Do not bring it into the country. Contact the seller for a refund or ask the original carrier to clear the block.

