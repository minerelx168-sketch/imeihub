## Common Mistakes to Avoid

- **Typing the IMEI wrongly** — one wrong digit makes the record useless. Copy it from `*#06#`.
- **Declaring only one IMEI** on a dual-SIM phone.
- **Buying a used phone without a blacklist check.**
- **Relying on old information** — rules and court orders may change, so verify with KRA.

## Frequently Asked Questions

**Is the IMEI declaration a tax?**
No. The declaration records your device. Normal customs duty rules still apply to goods above allowances.

**Do I need to declare a phone I will not use in Kenya?**
KRA's notice refers to devices you plan to use within Kenya. Check the current wording on the form.

**What if my IMEI is blacklisted?**
A blacklisted device may be blocked by local networks. Run a [blacklist check](https://imeihub.net/service.php?slug=blacklist) before travelling.
