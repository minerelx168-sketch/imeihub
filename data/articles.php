## "F88 Form" vs. the Kenyan Declaration

Many travellers search for the **F88 form phone check**. The F88 is actually the *Australian* passenger declaration card, so it is not used in Kenya. Kenya uses its own **KRA customs passenger declaration**, completed on arrival (paper or through the customs officer at the Red/Green channel). The principle is the same: you state what you are carrying, including **phones, tablets, laptops and smartwatches**, and the officer may ask for the **IMEI** to record it.

