## What Is the KRA IMEI Declaration?

The Kenya Revenue Authority (KRA) issued a public notice requiring passengers entering Kenya to **declare the IMEI numbers of the mobile devices they intend to use in the country**. The declaration is made on the **F88 customs declaration form** at the port of entry, and the rule was announced to take effect from **1 January 2025**.

The aim is to help KRA and the Communications Authority of Kenya (CA) tie devices to legitimate import records, reduce illicit and counterfeit handsets, and protect tax revenue.

> **Important:** The rule drew public and tourism-sector pushback and has faced legal challenge. Details can change, so always confirm the current requirement on the official [KRA website](https://www.kra.go.ke) or with the airline before you fly.

## Who Needs to Declare?

According to KRA's notice, the requirement applies to travellers bringing phones, tablets and other devices with IMEI numbers that they plan to use within Kenya:

- **Returning Kenyan residents** carrying new or second-hand phones
- **Visitors and tourists** who will use their own phone with a local SIM
- **Business travellers** and traders carrying several handsets

## How to Find Your IMEI Number

Your IMEI is a unique 15-digit identifier. Find it **before** you land:

- Dial `*#06#` on the keypad — the IMEI appears on screen
- **iPhone:** Settings > General > About
- **Android:** Settings > About phone > Status information
- Look at the SIM tray or the original box label

Dual-SIM phones have **two IMEIs**. Write down both.

## How to Fill in the F88 Form (Step by Step)

- Step 1: Collect the IMEI number(s) of every device you will use in Kenya.
- Step 2: Pick up the F88 form on the flight or at the arrivals hall.
- Step 3: Fill in your passport and flight details as normal.
- Step 4: In the section for mobile devices, write each IMEI clearly in block letters.
- Step 5: Hand the form to the customs officer and keep any receipt or stamped copy.

