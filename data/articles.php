## What Is the F88 Form?

The **F88** is the standard passenger customs declaration used at Kenyan entry points. It is where travellers list goods they are carrying that may be dutiable, restricted or need to be recorded, such as:

- Cash above the reporting limit
- Commercial quantities of goods
- **Electronic devices** such as new phones, laptops and tablets

For phones, the practical point is simple: **customs wants to know which devices are entering the country and to link each one to its IMEI**. This helps the authorities tell personal-use devices apart from commercial imports, and helps the regulator keep stolen or counterfeit devices off the network.

## Why Is the IMEI So Important?

Your **IMEI (International Mobile Equipment Identity)** is a unique 15-digit number that identifies your handset. In Kenya it is used to:

- **Match the device to a declaration** made at the border
- **Block stolen phones** through the national device management system run with the Communications Authority
- **Detect counterfeit or cloned handsets** that fail IMEI validation
- **Support tax compliance** on imported electronics

A phone with an invalid, duplicated or blacklisted IMEI can be refused service by Kenyan operators, no matter how much you paid for it.

## How to Find Your IMEI (Before You Land)

Do this at home, not at the customs desk:

- **Dial `*#06#`** on any phone. The IMEI(s) appear on screen. Dual-SIM phones show two.
- **iPhone:** Settings > General > About > scroll to IMEI.
- **Android:** Settings > About phone > IMEI information.
- **Physical check:** look on the SIM tray, the back of the phone or the original box.

Take a screenshot and keep a photo of the box label. If your phone is dual-SIM, note **both** IMEIs.

## Step-by-Step: Declaring Your Phone on Arrival

- **Step 1: Prepare your details.** Write down the make, model and IMEI of every phone you carry, plus the approximate value and whether it is new or used.
- **Step 2: Complete the declaration.** Fill in the customs declaration honestly, listing electronic devices where required. If you are unsure whether your phone must be listed, ask.
- **Step 3: Use the correct exit channel.** Follow the signs for declared goods if you have anything to declare. Do not walk through the "nothing to declare" lane with items that should be declared.
- **Step 4: Keep your paperwork.** Retain the declaration and any receipt. You may need it if your phone is later questioned on the network.
- **Step 5: Insert a local SIM only after checks.** If the phone is checked and clean, it should activate normally.

## Personal Phone vs. Commercial Import

| Situation | Typical Treatment | What to Do |
|---|---|---|
| Your own used phone, in use | Generally treated as personal effects | Note the IMEI, keep it on you |
| Brand-new phone in sealed box | More likely to be questioned | Declare it, keep the receipt |
| Several phones of the same model | Likely viewed as commercial | Expect duty; use proper import channels |
| Phone bought abroad for a friend | Treated as an import | Declare it and check the IMEI |

Exact thresholds and duty are set by KRA and can change, so verify current figures officially.

## Buying a Phone in Kenya? Check the IMEI First

The same IMEI logic protects **buyers in Nairobi, Mombasa and Kisumu** on the second-hand market. Before you pay, check that the phone:

- Is **not reported lost or stolen**
- Is **not blacklisted** by a carrier
- Has an **IMEI that matches** the model printed on the box and in the settings
- For iPhones, is **not iCloud-locked** or enrolled in MDM

## Common Mistakes That Cause Trouble at JKIA

- Not knowing the IMEI when asked
- Carrying multiple new phones without declaring them
- Buying a phone with a tampered or missing IMEI label
- Assuming an unlocked phone is a clean phone (unlocked does not mean not blacklisted)
- Discarding the receipt or proof of purchase

