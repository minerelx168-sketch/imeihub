## What Is the KRA F88 Form?

The **F88** is the customs declaration form used by travellers entering Kenya. You declare goods you are carrying that may be subject to duty, restricted, or otherwise of interest to customs. Since the 2025 change, mobile phones and similar devices are part of what the KRA expects you to account for, along with their IMEI numbers.

In plain terms:

- The **F88** is the paper or electronic declaration you hand to customs.
- The **IMEI** is the 15-digit serial number that uniquely identifies each phone.
- The **KRA** uses the declaration to record that a device entered the country legally.

## Why Kenya Wants Your IMEI

Kenya, like many countries, ties mobile devices to regulation for three reasons:

- **Revenue protection:** Making sure imported devices are declared and any duty owed is paid.
- **Counterfeit control:** Fake and cloned handsets often share duplicated or invalid IMEIs.
- **Theft and fraud prevention:** A stolen or blacklisted device can be flagged and blocked.

A device with a clean, genuine IMEI that was properly declared is far less likely to cause problems with customs or with local networks later.

