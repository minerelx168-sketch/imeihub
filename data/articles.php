### Where do I find my IMEI number?
Dial `*#06#`, or open Settings > About. You can also find it on the SIM tray or the box.

### Will my phone be blocked if I do not declare it?
Not automatically, but undeclared, stolen or counterfeit devices can be flagged and refused service. Declaring and keeping records reduces that risk.

