The **CEIR (Central Equipment Identity Register)** is Myanmar's national database of mobile phones allowed to connect to local networks. Every phone is identified by its **15-digit IMEI number**. Under the rules announced in 2026, a handset whose IMEI is not on the CEIR **whitelist** can be refused service on Myanmar mobile networks.

