## What Is the F88 Form?

The **F88** is the Kenya customs **passenger declaration form**. Every arriving passenger declares goods they carry, such as cash above the limit, commercial goods, and high-value personal electronics.

For phones, the declaration typically asks you to list:

- **Device type** (smartphone, tablet, laptop)
- **Brand and model**
- **IMEI number** (15 digits)
- **Whether it is for personal use or for resale**

## Which Phones Are Affected?

| Situation | Typical Treatment |
|---|---|
