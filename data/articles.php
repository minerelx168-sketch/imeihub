## Why Kenya Now Asks Travellers About Their Phones
Kenya tightened its handling of imported mobile devices to fight smuggling, counterfeit handsets and under-declared electronics. Since January 2025, travellers arriving at Kenyan airports are expected to **declare phones and other electronics** to the Kenya Revenue Authority (KRA) using the customs declaration process, commonly known as the **F88 form**.

If you are a tourist, a returning resident, a student or a reseller, the key point is the same: **your phone's IMEI is the identifier that links the device to you, to customs and to Kenyan mobile networks.**

