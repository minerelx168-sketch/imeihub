## What Is the F88 Form?
The F88 is the customs declaration form used on arrival in Kenya. You list goods you are carrying that may be dutiable or restricted. For phones, laptops and tablets, the declaration helps customs tell the difference between:

- **Personal-use devices** you are bringing in for your own use and will take home again.
- **Commercial or resale quantities** that may attract import duty and VAT.
- **New, boxed devices** versus used ones in daily use.

## What Information to Prepare
Have these details ready before you reach the customs desk:

- **Make and model** (for example, "Samsung Galaxy S24").
- **IMEI number(s)** — dual-SIM phones have two. Dial `*#06#` to display them, or look in *Settings > About phone*.
- **Approximate value** and, ideally, a receipt or invoice.
- **Purpose of the device** (personal use, gift, resale).
- Your passport and travel details.

## How to Find Your IMEI in 30 Seconds
- Dial `*#06#` on the keypad — the IMEI(s) appear instantly.
- On iPhone: *Settings > General > About*.
- On Android: *Settings > About phone > Status information*.
- Check the SIM tray or the back of the box if the phone will not turn on.

Write the number down or screenshot it **before** you travel. A 15-digit IMEI is also protected by a Luhn checksum, so a mistyped digit will fail validation.

