## Buying a Phone in Kenya? Check the IMEI First

The declaration rules are only half the story. If you are buying a **second-hand or imported phone in Nairobi** (River Road, Luthuli Avenue, Sarit Centre and online marketplaces), run an IMEI check **before paying**:

- **Match the IMEI** printed on the box, the SIM tray and in `*#06#`.
- **Check the blacklist** so you do not buy a stolen device that gets blocked later.
- **Confirm the model** returned by the check matches what the seller advertises.
- **Insist on a receipt** that records the IMEI.

Kenya also offers an official counterfeit-device check through the Communications Authority. Verify the current method and short code on the CA website before relying on it.

## Common Mistakes Travellers Make

- **Not declaring a new phone** still in its box. Unopened devices are the most likely to be questioned.
- **Carrying multiple identical phones** without explaining why.
- **Using an unreadable or altered IMEI sticker.**
- **Assuming an iPhone is automatically safe.** Cloned and refurbished-as-new devices exist for every brand.
- **Throwing away the receipt** before leaving the airport.

## Frequently Asked Questions

### Is the KRA IMEI declaration mandatory for every traveller?
Travellers carrying electronic devices should expect to declare them on the customs form when asked, and officers can request the IMEI. Personal-use devices are generally treated more leniently than commercial quantities, but you should always check KRA's current guidance.

### What happens if my IMEI is blacklisted?
A blacklisted or stolen IMEI can be refused network service and may lead to the device being seized or questioned. Check before you travel, not after.

