## Do You Need to Declare Your Phone's IMEI in Kenya?

If you are flying into Nairobi (JKIA) or Mombasa (Moi International) with a smartphone, tablet or laptop, you may be asked to **declare the device and its IMEI number** to the **Kenya Revenue Authority (KRA)** at the airport. Since January 2025, travellers have been steered toward declaring electronic devices on the customs declaration form (commonly called the **F88 form**), as part of Kenya's wider crackdown on counterfeit, smuggled and untaxed handsets.

This guide explains what the declaration is, what information you need, and how to confirm your IMEI is clean **before** you reach the arrivals hall.

> **Important:** Customs rules change. Always confirm current allowances, duty rates and procedures on the official KRA website or with an officer on arrival. This article is general guidance, not legal or tax advice.

## What Is the F88 Customs Declaration Form?

The **F88** is the passenger customs declaration form used by KRA Customs. Travellers list goods they are carrying, including high-value electronics. For phones, officers typically want to see:

- The **brand and model** (for example, Samsung Galaxy S25 or iPhone 16)
- The **IMEI number** (and the second IMEI on dual-SIM phones)
- Whether the device is **for personal use**, **a gift**, or **for resale**
- An approximate **value** or proof of purchase

Devices for personal use that you travel with and take back out are usually treated very differently from phones brought in for sale. Carrying several units of the same model is a red flag and may attract duty.

## What Is an IMEI and Why Does KRA Care?

An **IMEI (International Mobile Equipment Identity)** is the unique 15-digit serial number of a phone. Authorities use it to:

- **Link a device to duty paid** so legitimate imports are not taxed twice
- **Detect counterfeit or cloned handsets** that fail quality and safety standards
- **Block stolen phones** from local networks
- **Reduce under-valued and smuggled imports**

Kenya's **Communications Authority (CA)** also runs a device verification system that can disconnect counterfeit handsets from mobile networks, so a bad IMEI can cost you both at customs **and** on the network.

## How to Find Your IMEI in 30 Seconds

- **Dial `*#06#`** on any phone. The IMEI(s) appear instantly.
- **iPhone:** Settings > General > About, then scroll to IMEI.
- **Android:** Settings > About phone > Status information > IMEI.
- **Physical check:** Look at the SIM tray, the back of the phone or the original box label.

Write the IMEI down and take a screenshot. Officers may ask you to show it on the device itself.

## Step-by-Step: Declaring Your Phone at a Kenyan Airport

- **Step 1 – Check the IMEI before flying.** Confirm the phone is not blacklisted, reported stolen or fake (see the checklist below).
- **Step 2 – Gather documents.** Keep your receipt, warranty card or invoice, plus the phone box if you have it.
- **Step 3 – Fill in the declaration.** Complete the customs form on the plane or at the airport and list each device with its model and IMEI.
- **Step 4 – Choose the right channel.** If you have items to declare, use the **red channel**. Declaring honestly is far cheaper than a penalty.
- **Step 5 – Present the device if asked.** Be ready to dial `*#06#` so the officer can match the IMEI to your form.
- **Step 6 – Keep your receipt.** If duty is charged, keep the payment proof for the rest of your stay.

